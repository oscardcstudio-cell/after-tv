import assert from 'node:assert/strict';
import { tonDe, lumierePropre, reglages, creeWiggle, applique, filtre, LUM_PLANCHER } from './image.js';
const L = (lum, contraste) => ({ id: `l${lum}-${contraste}`, ton: [lum, contraste] });
const C = (couche, loop, extra = {}) => ({ couche, loop, opacite: 1, fusion: 'normal', ...extra });
assert.equal(tonDe({}), null);
assert.equal(tonDe({ ton: [0.2] }), null);
assert.deepEqual(tonDe(L(0.4, 0.2)), { lum: 0.4, contraste: 0.2 });
assert.equal(lumierePropre({ lum: 0.1, contraste: 0.1 }), 1);
assert.equal(lumierePropre(null), 1);
const b = lumierePropre({ lum: 0.45, contraste: 0.1 });
assert.ok(b < 1 && b > LUM_PLANCHER, `0.45 ramenée sans excès : ${b}`);
assert.equal(lumierePropre({ lum: 0.95, contraste: 0.1 }), LUM_PLANCHER);
let r = reglages([C(1, L(0.2, 0.15))], { section: 'break', bpm: 125 });
assert.equal(filtre(r.get(1)), 'none');
r = reglages([C(1, L(0.2, 0.15)), C(2, L(0.6, 0.3), { opacite: 0 })]);
assert.equal(r.has(2), false);
assert.equal(filtre(r.get(1)), 'none');
r = reglages([C(1, L(0.2, 0.1)), C(2, L(0.2, 0.3))]);
assert.equal(r.get(1).contraste, 1);
assert.ok(r.get(2).contraste < 1 && r.get(2).contraste >= 0.8);
r = reglages([C(1, L(0.2, 0.1)), C(2, L(0.2, 0.1), { fusion: 'plus-lighter' })]);
assert.ok(r.get(1).lum < 1 && r.get(2).sat < 1);
const un = [C(1, L(0.2, 0.15))];
assert.ok(reglages(un, { section: 'hyper', bpm: 120 }).get(1).contraste > 1.15);
assert.ok(reglages(un, { section: 'drop', bpm: 136 }).get(1).contraste > 1.1);
assert.equal(reglages(un, { section: 'drop', bpm: 124 }).get(1).contraste, 1);
let des = [0, 0.9];
const w = creeWiggle(() => des.shift() ?? 0);
assert.equal(w({ section: 'break', mesure: 1, maintenant: 0, bpm: 120 }), null);
des = [0, 0.9];
const coup = w({ section: 'drop', mesure: 10, maintenant: 1e3, bpm: 120 });
assert.ok(coup && coup.teinte === 8 && coup.jusqua === 1500);
des = [0, 0.9];
assert.equal(w({ section: 'drop', mesure: 14, maintenant: 3e3, bpm: 120 }), null);
des = [0, 0.1];
assert.equal(w({ section: 'hyper', mesure: 18, maintenant: 5e3, bpm: 120 }).teinte, -8);
const non = creeWiggle(() => 0.9);
assert.equal(non({ section: 'drop', mesure: 1, maintenant: 0, bpm: 120 }), null);
const f = filtre(applique({ lum: 1, contraste: 1, sat: 1, teinte: 0 }, coup));
assert.match(f, /brightness\(1\.12\)/);
assert.match(f, /hue-rotate\(8deg\)/);
console.log('image.test.mjs : ok');
const h = creeWiggle(() => 0);
assert.ok(h({ section: 'drop', maintenant: 0, bpm: 120 }));
assert.equal(h({ section: 'drop', maintenant: 1e4, bpm: 120 }), null);
assert.ok(h({ section: 'drop', maintenant: 16e3, bpm: 120 }));
console.log("image.test.mjs : mesure à l'horloge ok");
